/* 轮径（直径，单位 0.01mm）：实测 75mm -> 7500（= 0x1D4C，小端字节序 4C 1D）
 * ★ 课题一是虚拟轮径（只做单位换算），课题二是真实轮径，填错直接变成距离误差：
 *   0.5% 误差 = 5m 走偏 25mm。左右轮要分别标定。 */
#define CAR_LEFT_WHEEL_0P01MM           7500U
#define CAR_RIGHT_WHEEL_0P01MM          7500U

/* 轮距（左右轮中心距，单位 mm）
 *
 *  两个候选值，现在用**物理实测值 388**：
 *
 *    375 = 「有效轮距」，用拟合反推出来的
 *        两台电机各反向走 304.7mm（90° 弧长）时，陀螺仪实测转了 93.0°
 *        反推 2 x 304.7 / (93.01° x pi/180) = 375.4mm
 *        差的 3.3% 来自减速段过冲 + 轮子横向刮地
 *
 *    388 = 「物理轮距」，用尺子量两轮中心距得到的真实几何值
 *
 *  ★ 现在用 388 的原因：转角已经改成【陀螺仪闭环】了
 *    （Car_RotateToHeading，见 car_bringup.h 的 CAR_TST_YAW_*）。
 *    闭环会自己补转，所以这里填「物理真值」比填「拟合值」更合理 ——
 *    拟合出来的 375 其实是在补偿打滑，而打滑量随速度/地面变，
 *    提速之后那个 3.3% 已经不成立了。
 *    填 388 时开环会转少约 3.3%，闭环补一次就回来了。
 *
 *  ★ 只有关掉闭环（CAR_TST_YAW_CLOSE = 0）时，这个值才直接决定转角精度：
 *       转少了 -> 调大；转多了 -> 调小
 *
 *   ★ 换车或换地面后需要重新核对这个值。 */
/* 轮距（左右两轮接地中心间距，单位 mm）
 *
 * ★★★ 这个值已经过物理验证，不要再凭卷尺量了 ★★★
 *
 *  2026-10-27 用【开环转角】验证（Car_BuRunTurnTest，全程不读陀螺仪）：
 *      弧长 = 轮距 × π × 角度/360   直接下发，看车头转了多少
 *      结论：转 5 圈 360° 每次都精准回到原线
 *
 *  配合这个值的历史数据：
 *      gain=100%   + W=388.00  -> 车实际转 361.555°（陀螺仪也读 361.555°）
 *      gain=99.57% + W=388.00  -> 车实际转 360.000°（开环验证确认精准）
 *  两者都指向同一个物理真值：
 *      W_real = 388 × 360 / 361.555 = 386.331 mm
 *
 *  ★ 为什么能确定是轮距错而不是陀螺仪多读：
 *      若陀螺仪多读 0.43%，那么 gain=99.57% 时车只会转 358.45°，
 *      5 圈就差 7.7° —— 肉眼一眼能看出少转。
 *      实测"每次都精准到位"，所以只能是轮距填错了。
 *      陀螺仪一直是对的：静态漂移 0.02°/min、时间基 ppm=0、标度因子
 *      由这次开环验证独立确认。
 *
 *  ★ 0x0408 配轮径（75mm）实测完全不生效，所以距离标定靠
 *    CAR_BU_DIST_SCALE_PCT，与此处的轮距是两回事（那个管"走多远"，
 *    这个管"转多少度"）。
 */

/* ★★★ 2026-10-27 调参尝试：386.331 -> 386.82 ★★★
 *
 *  背景：5 个来回落点左偏 2~5cm。左偏的机制已推导清楚：
 *      少转 δ  ->  从 0° 转到 (180−δ)°，方向向量 (−cos δ, +sin δ)
 *      第 2 段走 5m  ->  y 位移 = +D·sin(δ)  ->  y > 0 = 往左偏
 *      所以「少转 = 左偏」，要纠左偏就得让掉头【多转】-> 轮距【调大】
 *
 *  幅度：按 2cm 那次的残余 0.229° 补，不按 5cm 补。
 *      0.229° 需要补弧长 = 0.229 × (π×386.331/360) = 0.77mm
 *      180° 弧长 = 386.331 × π/2 = 606.85mm
 *      新轮距 = 386.331 + 0.77/(π/2) = 386.82mm   (+0.127%)
 *
 *      ★ 为什么不按 5cm 补（那要到 387.56）：
 *        回滚后参数与 2cm 那版完全相同，结果却是 5cm，
 *        说明单次测量重复性差，2cm/5cm 的差异里含很大噪声。
 *        按噪声调参会把系统调歪，所以取保守幅度。
 *
 *  ★ 这个调整的代价（必须知道）：
 *      调大轮距会让【所有】转角都多转，不只 180°：
 *          180° 多转 +0.229°（正好补掉左偏）
 *          360° 多转 +0.458°（这是副作用）
 *      也就是说它不是真正的"修正"，只是把误差从 180° 挪到了 360°。
 *      如果之后做开环 360° 测试，会发现又"多转"了 —— 那是正常的。
 *
 *  ★ 判据：再跑 5 个来回看落点。
 *      变小 -> 方向对了，可以继续微调
 *      变大 -> 方向反了（说明我推导的符号或实际偏向记反了），改回
 *      不变 -> 5cm 是噪声，调轮距无效，得改算法（抖动法）
 *
 *  ★ 想彻底分清「系统性偏」还是「随机噪声」：
 *      同一份固件连跑 3 次记落点。分布宽 = 噪声，调参无用。
 */
#define CAR_WHEEL_BASE_MM               386.82f

