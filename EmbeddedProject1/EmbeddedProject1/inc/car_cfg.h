/* ★★★ 马达号（协议文档里被误标成"设备号"的那个字段）★★★
 *
 * 协议 V1.1 有两个长得一样的字段，文档都叫"设备号"，实际是两个完全不同的东西：
 *     0x0313 Data[7]         = 设备号（SN 槽位）——只决定 0x0316 写给谁
 *     0x0316 Byte6 bit3..0   = 马达号        ——★ 决定 0x0413~0x0419 的 Data[4] 寻址谁
 *
 * 出厂时两台电机的马达号都是 0，于是 Data[4]=0 的每条命令两台一起执行：
 *     一个 +位移 一个 -位移 -> 互相抵消，车只能原地打转，永远走不出直行。
 * 把其中一台设成马达号 1 之后，总线立刻分开（实测）：
 *     Data[4]=0 -> 1 个 ACK， Data[4]=1 -> 1 个 ACK
 *     只驱动马达号 0：0x0420 剩余位移递减，0x0421 纹丝不动。
 *
 * ★ 主帧 / 从帧不能各带一个轮子！
 *   0x0420 一帧里的主、从两个 s32 是同一台电机的两个控制入口，不是两个物理轴。
 *   实测：主 +2000 / 从 -2000 -> 转角 0.1°（互相抵消，车根本没动）。
 *   正确做法是两个轮子都走主帧，靠马达号 0 / 1 区分：
 *       0x0416 Data[4]=0 +3000  与  0x0416 Data[4]=1 -3000  ->  转角 0.00°（直行）
 *       0x0416 Data[4]=0 +3000  与  0x0416 Data[4]=1 +3000  ->  转角 51.95°（原地转） */
#define CAR_LEFT_DEV                    0x00U   /* 左轮马达号 */
#define CAR_RIGHT_DEV                   0x01U   /* 右轮马达号 */

/* 帧通道选择：两个轮子都用主帧组 0x0414 / 0x0415 / 0x0416（DLC=6，带目标类型字节），
 * 靠上面的马达号区分左右。★ 不要改成 0（从帧组），主从同时用会互相抵消。 */
#define CAR_LEFT_USE_MAIN_FRAME         1U
#define CAR_RIGHT_USE_MAIN_FRAME        1U

/* 电缆/机械镜像带来的方向差异：1 = 该电机正方向反装（写进 0x0316 的 Byte6 bit7）
 * ★ 实测两台电机是镜像安装的：同一条「+位移」指令，一台正转、一台反转。
 * ★★ 现在方向【不再写死】：运行时由 Car_AutoDetectDirections() 测出来，
 *    结果放进 g_car_dir_sign[]，运动函数自动套用（见 car_bringup.h 的
 *    CAR_BU_DIRDET_*）。所以这里两条都保持 0，不要在这层取反 ——
 *    两层同时反会抵消回原样，而且换车就错了。 */
#define CAR_LEFT_DIR_REVERSED           0U
#define CAR_RIGHT_DIR_REVERSED          0U

/* --------------------------------------------------------------------------
 *  ★★★ 运行时方向表初值（设备0 / 设备1 的「车前进方向」符号）★★★
 *
 *  语义：Bu_StartMotion(left, right) 里 left/right 是【物理前进量】，
 *        内部转成 Bu_EmitMotion(left*S0, right*S1)。
 *          S = +1 -> 该电机「原始 + 位移」= 车前进
 *          S = -1 -> 该电机「原始 + 位移」= 车后退（需要取反）
 *
 *  ★ 只有两种合法组合（直行必须是异号）：
 *        { +1, -1 }  设备0 正方向=前进，设备1 需取反
 *        { -1, +1 }  设备0 正方向=后退，设备1 需取反
 *     若填成同号（{+1,+1} / {-1,-1}），直行会变成【原地转圈】。
 *
 *  ★ 两者互为整体取反，会【同时】反转直行和转向：
 *        直行 (d,-d) -> (-d,+d)    前进 <-> 后退
 *        转向 (a,+a) -> (-a,-a)    左转 <-> 右转
 *     所以"车倒着走"一定是这两个互换，不存在只反一个的情况。
 *
 *  ★ 2026-10-27 改为 { -1, +1 }：
 *     用户实测「车倒着到达对面」，说明 { +1, -1 } 让两轮都反了。
 *
 *  ★ 怎么确认：CAN 0x7F0 帧会实时上报当前生效的 S0 / S1。
 *    改这里不用动 car_bringup.c，烧录后看 0x7F0 即可核对。
 * -------------------------------------------------------------------------- */
#define CAR_LEFT_DIR_SIGN               (+1)    /* 设备0（g_car_dir_sign[0]）*/
#define CAR_RIGHT_DIR_SIGN              (-1)    /* 设备1（g_car_dir_sign[1]）*/

/* 设备 SN（7 字节）。
 * ★ 实测：电机上电后不绑定 SN，只会回 ACK、不转也不报位移，所以必须逐台绑定。
 * ★★ 0x0313 靠 SN 匹配来"认领"电机：SN 对不上，总线上没有任何电机会接受这条绑定，
 *    于是两台都没有设备号 0/1，后面所有 0x0316/0x0408/0x0413/0x0416 全部落空 ——
 *    表现就是「上位机能开、STM32 完全不动」。
 *
 * ★★★ 现在 SN 也【不再写死】：优先用电机上电自己广播的 0x0312
 *       （motor.c 收集两条不同 SN -> Bu_ResolveSn() 按设备号分配）。
 *       下面这两行只是**兜底**：只有当上电广播一条都没收到（电机没广播/没接）
 *       或者只收到一条时才会用到。
 *
 *       所以换车、换电机都**不用再改这里**。
 *
 * 当前写下的是「车2（新）」实测广播值（分析仪抓到的 0x0312）：
 *     19 09 16 07 37 AB 00
 *     19 09 17 07 A3 AC 00
 *
 * 车1（旧）的 SN（万一需要临时兜底回去时用这两行）：
 *     19 09 16 07 D0 AA 00
 *     19 0A 09 07 49 CB 00
 *
 * ★ 哪台装左边也【不用猜】：推车 + 陀螺仪自动识别（Car_AutoDetectDirections）。
 */
#define CAR_LEFT_SN_BYTES               0x19U, 0x09U, 0x16U, 0x07U, 0x37U, 0xABU, 0x00U
#define CAR_RIGHT_SN_BYTES              0x19U, 0x09U, 0x17U, 0x07U, 0xA3U, 0xACU, 0x00U

#define CAR_LEFT_SN                     { CAR_LEFT_SN_BYTES }
#define CAR_RIGHT_SN                    { CAR_RIGHT_SN_BYTES }

/* 主动索取 SN 时使用的"设备类型"字节（0x060D 的 Data[0]，协议文档未给取值）
 * 0x00 是保守猜测；用 0x0312 被动接收更可靠。 */
#define CAR_MOTOR_SN_DEVTYPE            0x00U

