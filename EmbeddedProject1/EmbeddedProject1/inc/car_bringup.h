/* ★★★ 等运动真正走完再下一条 —— 这是防止电机被搞死的关键
 *
 *  实测事故：段「前进 +2000/+2000」走了 155 帧反馈还在收尾（从通道剩余位移
 *  还有 1372 = 137mm），固件就照固定 3 秒延时下了「后退 -2000/-2000」。
 *  结果 1.6 秒后电机彻底不响应：位移/力矩/心跳/ACK 全 0，
 *  连补发绑定都救不回来，只能断电重启。
 *  ⇒ 绝不能在轴还在动的时候下发反向指令。改成轮询剩余位移归零再走下一步。
 *
 *  剩余位移从 0x0420 反馈里取（motor.c 已解析到 g_motor_remain_left/right）。
 */
#define CAR_BU_REMAIN_EPS_0P1MM     30        /* 剩余 < 3mm 视为到位 */
/* ★ 发指令后最多等多久才认定"这个行程本来就很小、反馈可能不出现忙"。
 *   见 Bu_WaitMotionDone()：必须先看到过"忙"才认"闲"，
 *   否则会在运动刚开始时就误判到位，把下一段指令插进来。 */
#define CAR_BU_REMAIN_SEEN_MS       400U
#define CAR_BU_MOTION_SETTLE_MS     200U      /* 到位后再稳一下（原 250；别减到 150 以下，
                                               * 减速段车还在滑，读陀螺仪会读到"正在滑"的中间值）*/
#define CAR_BU_SEQ_MOVE_TIMEOUT_MS  20000U    /* 单步最长等 20s
                                               * ★ 实测 8s 不够：500mm @ 60mm/s 理论要 8.33s，
                                               *   加上标定系数放大后电机可能限速，实际更久。
                                               *   stage 实测耗时 10.5s（= 8s 超时 + 0.25s settle
                                               *   + 2s 间隙）说明每步都在卡超时被截断，
                                               *   车只走到 ~480mm 就被下一条指令打断。 */

/* 诊断段：让两轮各走 π×75 = 235.62mm 的线位移，数轮子转几圈
 *   ★ 运动时间 = 235.62mm ÷ CAR_BU_DIAG_MMPS = 235.62 ÷ 30 = 7.85s
 *     —— 这个时间和"电机内部轮径是多少"无关：轮径错 n 倍时，
 *        电机把位移少算 n 倍、把速度也少算 n 倍，两者相抵，用时不变。
 *   所以诊断后的等待必须 ≥ 8s，否则轮子还在转就下发直行指令，
 *   电机丢弃旧目标，圈数就数不准了。
 *   想缩短总时间：把 CAR_BU_DIAG_MMPS 调大（如 60），等待同步减半（如 4500）。 */
#define CAR_BU_DIAG_MMPS            30.0f     /* 诊断时轮子线速度 mm/s（慢，方便数圈） */
#define CAR_BU_DIAG_WAIT_MS         10000U    /* 诊断后等待：7.85s 运动 + 2s 余量 */

/* 一次整圈对应的线位移 = π × 轮径(mm)。用于诊断"电机内部轮径到底多少" */
#define CAR_BU_ONE_REV_MM           235.6194f

