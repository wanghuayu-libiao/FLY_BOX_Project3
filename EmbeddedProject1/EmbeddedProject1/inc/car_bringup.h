/* ★★★ 马达号：左右轮必须是不同的值 ★★★
 *
 * 协议 V1.1 有两个都叫"设备号"的字段，含义完全不同：
 *     0x0313 Data[7]       = 设备号（SN 槽位）—— 只决定 0x0316 写给谁
 *     0x0316 Byte6 bit3..0 = 马达号        —— ★ 决定每条运动帧 Data[4] 寻址谁
 *
 * 出厂两台电机的马达号都是 0，于是 Data[4]=0 的命令两台一起执行，差速永远不成立。
 * 实测把一台设成 1 之后：
 *     Data[4]=0 -> 1 个 ACK， Data[4]=1 -> 1 个 ACK
 *     只驱动马达号 0：0x0420 剩余位移递减，0x0421 纹丝不动
 *
 * ★★ 两个轮子都走主帧组，只靠马达号分左右。千万不要一个用主帧一个用从帧：
 *    0x0420 一帧里的主、从两个 s32 是同一台电机的两个控制入口，不是两个物理轴。
 *    实测 主 +2000 / 从 -2000 -> 转角 0.1°（互相抵消，车根本没动）。
 *    正确（两者都走主帧 0x0416）：
 *        Data[4]=0 +3000  &  Data[4]=1 -3000  ->  转角 0.00°  直行 ✅
 *        Data[4]=0 +3000  &  Data[4]=1 +3000  ->  转角 51.95° 原地转 ✅
 *
 * ★ 掉电会丢失马达号，所以每次收到电机上电广播 0x0312 都要重设（见 Car_Motor_Init）。 */
#define CAR_BU_LEFT_MOTOR_NO        0x00U   /* 左轮马达号 / 设备号 */
#define CAR_BU_RIGHT_MOTOR_NO       0x01U   /* 右轮马达号 / 设备号 */

/* 初始化每一步之间的等待（ms） */
#define CAR_BU_STEP_DELAY_MS        50U
/* 配轮径连发 3 次，每次之间的间隔（ms） */
#define CAR_BU_WHEEL_GAP_MS         10U
/* 配轮径连发次数（协议要求"重复 3 次写入"） */
#define CAR_BU_WHEEL_REPEAT         3U

/* 是否补发加速度帧（0x0414 主 / 0x0417 从）。
 * ★ 实测：位置模式下电机没收到加速度会只回 ACK、剩余位移不减少（不动），
 *   所以初始化末尾补一条，且每次运动前再补一条。 */
#define CAR_BU_SEND_ACCEL           1
/* 加速度（0.1mm/s^2），2000 = 200mm/s^2 */
#define CAR_BU_ACC_0P1MMPS2         2000U

/* 初始化末尾给两个通道配的默认速度（mm/s），之后每次运动前会再覆盖 */
#define CAR_BU_DEFAULT_SPEED_MMPS   100.0f

/* 运动帧之间必须留的间隙（ms）。
 * ★ 实测：加速度/速度/位置帧连发会被电机丢弃，必须一条一条隔开发。 */
#define CAR_BU_MOTION_GAP_MS        20U

