/**
  * @brief  发一帧 STM32 心跳（0x7FE），由 Task_CanHeartbeat 每 500ms 调用一次
  *
  *         数据布局：
  *             [0] 0xA5 固定魔数    [1] 序号（0~255 循环，一直在变 = STM32 活着）
  *             [2] 序列阶段
  *             [3] 低 4 位 = 初始化完成；高 4 位 = 上电时收到的 0x0312 广播条数
  *                 （广播 0 条 = 上电时一台电机都没起来：没电 / CAN 断开 / 没上电）
  *             [4] tx_fail 低字节   [5] tx_count 低字节
  *             [6] tx_fail 高字节   [7] tx_count 高字节
  *
  *         判读方法：
  *             看得到 0x7FE 且 [1] 在变  -> STM32 的 CAN 发送链路完全正常，问题在报文内容/设备号
  *             看不到 0x7FE              -> STM32 的 CAN 收发器、接线或波特率有问题
  *             [3] 高 4 位 = 0           -> 上电时电机没广播 0x0312（电机没电/没接）
  * @param  None
  * @retval None
  */
void Car_BuSendHeartbeat(void);

/**
  * @brief  发一帧「固件里配置的 SN」（0x7FD），左右轮交替，每 2 秒一次
  *
  *         ★ 零风险自检：只需 CAN 分析仪，不用上位机、不用日志
  *           把这条帧的 Data[0..6] 和电机上电广播的 0x0312 逐字节对比：
  *               完全一致 -> SN 正确
  *               不一致   -> 改 car_cfg.h 的 CAR_LEFT_SN_BYTES / CAR_RIGHT_SN_BYTES
  *
  *         Data[0..6] = SN（7 字节，与 0x0312 广播同格式）
  *         Data[7]    = 0 左轮 / 1 右轮
  * @param  dev  0 = 左轮，1 = 右轮
  * @retval None
  */
void Car_BuSendSnInfo(uint8_t dev);

/**
  * @brief  ★ 把诊断结果广播到 CAN（两帧，见 CAR_DIAG_ANGLE_ID 的格式说明）
  *
  *         由 Task_CanHeartbeat 每 CAR_BU_DIAG_MS 调一次。
  *         这样不接调试器、不开上位机，只用一个 CAN 分析仪就能读到
  *         转角误差分辨测试的全部结果 —— 外部独立核对比口述可靠。
  *
  *         数据来源：g_car_angchk_* / g_car_turn_arc_off / g_car_turn_gain
  * @param  None
  * @retval None
  */
void Car_BuSendDiag(void);

/**
  * @brief  双电机绑定初始化（阻塞约 0.5 秒）
  *         严格按顺序：绑定 SN(0x0313 ×2，左右各绑一次) -> 配参数(0x0316) -> 配轮径(0x0408 ×3)
  *         末尾给主/从两个通道各配一次加速度(0x0414/0x0417)和速度(0x0415/0x0418)
  *
  *         ★★★ 两条实测铁律 ★★★
  *           1) 0x0316 只能写一次。写第二次电机立刻停止上报位移/力矩/心跳并停止回 ACK，
  *              实测「写 1 次 -> 位移 61 心跳 6 持续稳定」「写第 2 次 -> 8 -> 0 彻底不动」。
  *              所以只有检测到电机真的重新上电（收到 0x0312 广播）时才允许写。
  *              以前每次烧录/复位 STM32 都无条件写一次，把电机写死 ——
  *              这就是「只动左轮 / 右轮不动 / 电机锁住不动」反复出现的总根源。
  *           2) 0x0413（0x5A 使能 / 0x4A 释放）绝对不要发。一发就把电机搞死，
  *              而且完全不需要：不发它直接发位置指令，0x0420 立刻返回 151 帧，
  *              主通道 +952 / 从通道 -974，两轮反向差速正常。
  *
  *         设备号两台都是 0x00（改不动），左右轮靠主帧组 / 从帧组区分。
  * @param  None
  * @retval None
  */
void Car_Motor_Init(void);

