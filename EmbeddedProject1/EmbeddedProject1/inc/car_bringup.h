/* --------------------------------------------------------------------------
 *  距离标定系数（百分数，100 = 按 75mm 轮径原样下发，不做补偿）
 * --------------------------------------------------------------------------
 *  为什么需要：位移报文里只有"线位移(mm)"，电机要用它自己内部保存的轮径把
 *  线位移换算成转角/圈数。如果电机内部轮径不是 75mm（0x0408 没写进去，或被
 *  上电复位成出厂值），位移就会被错算：
 *
 *      电机实际走的距离 = 下发距离 × (75 / 电机内部轮径)
 *
 *  设 S = 电机内部轮径 / 75，则把下发的「距离和速度」都乘 S，实际运动就对了。
 *  （速度和距离同时乘 S，加速时间不变，所以只调这一个数就够。）
 *
 *  从实测反推（目标原地转 90°，实际目测约 25°）：
 *      实际角 / 目标角 = 75 / Dm = 25 / 90   ->  Dm ≈ 270mm  ->  S ≈ 3.6  ->  填 360
 *      若实测是 22.5°，则 Dm ≈ 300mm -> S = 4.0 -> 填 400
 *
 *  标定步骤（配合 Car_BuDiagWheelOneRev() 一起用最稳）：
 *      1) 先保持 100，下发 90° 原地转，量出实际转过的角度 A
 *      2) CAR_BU_DIST_SCALE_PCT = 100 × 90 / A
 *      3) 重新烧录后再转 90°，确认基本对上
 *  注意：这只是补偿，根因（0x0408 轮径没生效）仍然要用诊断函数查。
 */
#ifndef CAR_BU_DIST_SCALE_PCT
/* ★★ 当前 = 293.0（2026-10-26，按同事实测值试跑）
 *
 *   ★ 先证明了一件事：0x0408 轮径配置根本不生效。
 *     把轮径从 7500(75mm) 改成 23562(π×75mm) 写入两台电机后，
 *     下一轮 90° 转向实测仍是 30.09° / 30.01°，一个字都没变。
 *     （若电机认这个字段，转角应该变成 9.5°。）所以只能软件补偿。
 *
 *   这个系数的物理含义只有一个：
 *       S = 电机固件以为的轮径 D_m ÷ 你实际的轮径 D_real × (1 + 打滑率)
 *
 *   两个来源不同的值：
 *      301.5 = 本车用「卷尺量地面距离」标出来的 -> D_m ≈ 75 × 3.015 = 226mm
 *      293.0 = 同事实测（75mm 轮径 / 388mm 轮距那台）-> D_m ≈ 75 × 2.93 = 220mm
 *
 *   差 2.8%。同一型号电机不可能差 6mm，所以两个数里至少有一个把
 *   「打滑」算进去了：
 *      用卷尺量地面走过的距离 -> 含打滑 -> 系数偏大
 *      数轮子转了几圈（几何法）-> 不含打滑 -> 系数偏小
 *   两者可以互相换算，见下面「几何法自检」。
 *
 *   ★ 几何法自检（不用卷尺，1 分钟出结果）：
 *      1) 架空小车，调 Car_BuDiagWheelOneRev()（下发 π×75 = 235.62mm）
 *      2) 数轮子辐条转了几圈 N
 *      3) 物理含义：下发 235.62 × S 的位移，电机按 D_m 算，实际转 N 圈
 *             N = 235.62 × S / (π × D_m)
 *         要让 N = 1（下发一圈周长正好转一圈）：
 *             S_new = S_cur / N
 *         例：S=301.5 时数到 1.03 圈 -> S_new = 301.5 / 1.03 = 292.7 ≈ 293
 *             （正好对上同事那个 2.93x，说明差异就是打滑/地面）
 *
 *   ★★★ 301.5 时代的实测记录（留作对照，速度为 60mm/s、30°/s）
 *       原地左转  +90.00°  +90.01°
 *       原地右转  -89.97°  -90.17°
 *       直行 500mm 漂移  前进 -0.03° / -0.02°   后退 +0.05° / -0.17°
 *       指令换算：直行 15075 = 1507.5mm 指令 -> 物理 500.0mm
 *
 *   ★ 这个系数同时作用于「距离」「速度」「加速度」
 *     （Bu_MmTo0p1mm / Bu_MmpsTo0p1mmps / Bu_AccTo0p1mmps2），
 *     所以改它不会改变运动时间，两轮同步性也不受影响。
 *
 *   重新标定步骤：
 *      1) 下发直行 2000mm（别用 500mm，卷尺 ±5mm 就是 1% 误差），量实际 A(mm)
 *      2) CAR_BU_DIST_SCALE_PCT = 旧系数 × 2000 / A
 *      3) 若开着闭环，转角不用再调；关掉闭环才需要 CAR_WHEEL_BASE_MM = 388 × 90 / B
 */
#define CAR_BU_DIST_SCALE_PCT       293.0f
#endif

/* --------------------------------------------------------------------------
 *  ★★★ 转角增益（百分数，100 = 不补偿）★★★
 *
 *  作用：只影响「原地转向」的弧长，不影响直行距离和速度。
 *        在 Car_RotateInPlaceEx / Car_RotateInPlaceWheel 里乘到弧长上。
 *
 *  ★★★ 2026-10-27 结论：这里恢复 100，误差全部归到轮距里了 ★★★
 *
 *  原先这里填 99.57，是为了补掉"每圈多转 1.555°"。但后来用
 *  【开环转角验证】（Car_BuRunTurnTest，全程不读陀螺仪）发现：
 *      gain=99.57% 时开环转 5 圈 360°，每次都精准回到原线。
 *  这说明"多转 1.555°"不是打滑、也不是陀螺仪读数偏，
 *  而是 CAR_WHEEL_BASE_MM 填大了：
 *      真实轮距 = 388 × 360 / 361.555 = 386.331 mm
 *
 *  ★ 为什么能确定不是陀螺仪偏：
 *      若陀螺仪多读 0.432%，那 gain=99.57% 时车只会转 358.45°，
 *      5 圈差 7.7°，肉眼一眼能看出少转。实测"每次都到位"，
 *      所以只能是轮距错、陀螺仪对。
 *      陀螺仪另外两项也已独立验证：静态漂移 0.02°/min、时间基 ppm=0。
 *
 *  ★ 所以现在：CAR_WHEEL_BASE_MM = 386.33（物理真值），本增益 = 100。
 *    两个参数不再互相抵消，语义干净。
 *
 *  ★ 什么时候还要调这个值：
 *      换地面（瓷砖↔地毯）、换速度导致打滑变化时，用 SPIN 模式
 *      或 Car_BuRunTurnTest 重新标，然后填到这一行。
 *      它只该用于「补偿打滑」这类会随条件变化的东西，
 *      不该用来消化一个填错的几何常量。
 *
 *  ★ 运行期会被 Car_BuRunSpinCal() 覆盖（CAR_SPIN_APPLY_GAIN=1 时），
 *     但那只在当前这次上电有效；断电后回到这里写的值。
 *     所以想永久生效就改这一行。
 *
 *  ★ 100     = 不补偿（当前）
 *     99.57   = 补偿掉 0.432% 的"转多了"
 *     100.43  = 反过来，补偿"转少了"
 * -------------------------------------------------------------------------- */
#ifndef CAR_BU_TURN_GAIN_PCT
#define CAR_BU_TURN_GAIN_PCT        100.0f
#endif

/* --------------------------------------------------------------------------
 *  ★★★ 转角「固定弧长」补偿（齿隙 / 静摩擦 / 电机死区）★★★
 *
 *  ★★★ 这一条和前一个「增益」是不同的东西，必须分清 ★★★
 *
 *      增益误差（按比例）：转 360 偏 1.4° -> 转 90 只偏 0.35°
 *                          原因：轮距/打滑，误差 ∝ 角度
 *                          修法：CAR_BU_TURN_GAIN_PCT（乘一个系数）
 *
 *      固定偏移（与角度无关）：转 360 偏 1.4° -> 转 90 也偏 1.4°
 *                          原因：齿轮齿隙、静摩擦、电机最小步进 ——
 *                                每条指令开头的几毫米弧长"喂给间隙"了，
 *                                这是【固定量】，不随角度增长
 *                          修法：本宏（加一个固定弧长）
 *
 *  ★★ 为什么一定要分清：
 *      用增益去修固定偏移，只能在对标定时的那个角度正确。
 *      实测：拿 360° 标出来的 99.61% 去修固定偏移，
 *            360° 恰好抵消（巧合），但 90° 还剩 1.05° 误差。
 *      反过来用固定弧长去修增益误差也一样：90° 修好了，360° 就过头。
 *
 *  ★ 怎么判（用 CAR_BU_RUN_ANGLECHK 模式实测）：
 *      分别转 90° / 180° / 360°，看误差
 *          e90 ≈ 0.25 × e360  -> 增益误差
 *          e90 ≈ e360          -> 固定偏移
 *
 *  ★ 单位与符号：
 *      单位 mm，是【每轮】的物理弧长，正数 = 多补一点（治"转不够"）。
 *      1.4° 对应 1.4 × 3.386 = 4.74 mm
 *      0 = 不补偿
 *
 *  ★ 等效：这个量除以 CAR_BU_ARC_K 就是对应的角度补偿量。
 * -------------------------------------------------------------------------- */
#ifndef CAR_BU_TURN_ARC_OFFSET_MM
#define CAR_BU_TURN_ARC_OFFSET_MM   0.0f
#endif

