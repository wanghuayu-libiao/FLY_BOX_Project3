/**
  ******************************************************************************
  * @file    flybox.h
  * @brief   课题三·飞箱推拉箱机构（5 台 CAN 电机 + TOF8 测距）
  *
  *  ★★★ 机构拓扑（5 台电机 = 4 个自由度）★★★
  *
  *    ┌─ M1 左皮带电机 ┐
  *    │                 ├─ 纵向输送箱子（两台必须严格同步）
  *    └─ M2 右皮带电机 ┘
  *
  *    M3 前后电机（同步带 + 直线导轨）    → 抓钩平台前后直线往复
  *    M4 平台旋转电机（平台下方）          → 平台水平转 0°(工作位) / 90°(让位)
  *    M5 抓钩电机（平台上方）              → 抓钩抬 0°(垂下) / 90°(伸入箱子侧边凹槽)
  *
  *  ★★★ 为什么要分「工作位 / 让位」★★★
  *    抓钩平台卡在两条皮带的间隙里。抓钩垂放时突出于皮带平面，
  *    箱子要从皮带上面通过就必须先让平台右转 90° 退出通道。
  *    所以：要抓箱/推箱 -> M4 回 0°；箱子要在皮带上走 -> M4 到 90°。
  *
  *  ★★★ 最重要的一条约束：没有极限限位挡块 ★★★
  *    机构上【没有】硬限位，「撞停找原点」这条路走不通，而且撞一下就是结构损伤。
  *    因此这里的一切运动都必须是可以算出来的位置运动，靠三重保护：
  *
  *      ① 软件限位   —— FLY_AXIS_* 的 min/max（下面第 4 节），越界直接拒绝下发
  *      ② 行程限幅   —— 任一次点动的距离不得超过 FLY_JOG_MAX_MM
  *      ③ 到位确认   —— 每次运动必须等到 0x0420 剩余位移归零才算完成，
  *                      没确认到就【绝不】发下一条位置指令
  *                      （中途改目标会把电机搞死，课题二已实测过）
  *
  *    上电位置从哪来：靠电机自报的绝对位置（0x0408 / 通道 0x08），
  *    见 Fly_RequestPositions()。★ 这个绝对位置断电后是否保持，必须实测确认，
  *    见 flybox.c 里 Fly_Init() 的说明。
  *
  *  ★★★ 协议地址 ★★★
  *    设备号 == 马达号，同一个地址空间：
  *      0x0313 绑定  B7        = 设备号
  *      0x0316 参数  Byte7     = 设备号；Byte6 bit3..0 = 设备号（★ 飞箱保持原值）
  *      0x0408 配轮径 B0        = 设备号
  *      0x0413/14/15/16 Data[4] = 设备号
  *      0x0420+dev / 0x0440+dev / 0x0380+dev 的 dev = 设备号
  *    飞箱的 5 台设备号【出厂固定】，固件只能读、不能改。
  ******************************************************************************
  */

