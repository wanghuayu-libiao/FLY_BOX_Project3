/* =========================================================================
 *                   2. 设备号配置
 *
 *  ★★★ 结论：设备号出厂已经分好了，不需要绑定 ★★★
 *
 *    实测（2026-10-29，CAN 分析仪）：
 *        M1=7  M2=8  M3=9  M4=10  M5=11
 *
 *    所以 0x0313 SN 绑定那一步可以完全跳过 ——
 *    绑定的唯一目的就是「把设备号写进去」，既然已经有了，重复写没意义，
 *    反而多一次「写错就把号搞乱」的风险。
 *
 *    ★ 怎么确认这 5 个号是真的：
 *        5 台全部上电，抓 0x0420，应当出现 0x0427 / 0x0428 / 0x0429 /
 *        0x042A / 0x042B 五种不同 ID（而不是只有一个 0x0420）。
 *        因为 CAN 位仲裁会把「同 ID 同数据」的帧合并成一帧，
 *        能看到 5 个不同 ID 就证明 5 台的号确实不同。
 *
 *  ★ 设备号 == 马达号
 *    car_bringup.c 已实机确认：0x0316 的 Byte6 bit3..0（马达号）就是
 *    0x0413/14/15/16 里 Data[4] 用来寻址的那个号，同一个地址空间。
 *    所以每台电机只需要一个号。
 *    ★ 如果上电后「0x042X 有反馈，但发 0x0416 Data[4]=7 电机不动」，
 *      说明这两者不同，需要重新标定（见 flybox.c 的 Fly_ProbeMotorNo）。
 *
 *  ★ 为什么 7..11 完全没问题
 *      motor.c 内部缓存 MOTOR_DEV_SLOTS = 16，有效范围 0..15；
 *      反馈帧 0x0427~0x042B / 0x0447~0x044B / 0x0387~0x038B
 *      全部落在各自的 16 槽窗口内，不会和别的东西冲突。
 * ========================================================================= */

#define FLY_DEV_UNKNOWN                 0xFFU

