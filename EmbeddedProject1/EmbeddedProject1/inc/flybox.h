#define FLY_DEV_BELT_R                  8U      /* M2 右皮带 */
#define FLY_DEV_SLIDE                   9U      /* M3 平台前后 */
#define FLY_DEV_SWING                   10U     /* M4 平台旋转 */
#define FLY_DEV_HOOK                    11U     /* M5 抓钩 */

/* =========================================================================
 *              2.05 ★ 方向符号（+1 = 与逻辑方向一致，-1 = 反装需取反）
 *
 *  ★ 为什么必须有这一层：
 *    电机装到机构上时，有的是正向装、有的是镜像反装。
 *    同一条「+1000 单位」，装反的那台会往相反方向走。
 *    如果不在这里取反，就得在每个调用点手工写负号 ——
 *    迟早漏一个，而且「软限位」在逻辑帧里会算错。
 *
 *  ★ 实测结果（2026-10-29 现场，点动自检观察到）：
 *      M1 左皮带    方向反了   -> -1   （2026-10-29 第二次修正：原 +1 实测反向）
 *      M2 右皮带    方向反了   -> +1   （2026-10-29 第二次修正：原 -1 实测反向）
 *      M3 平台前后  方向反了   -> -1
 *      M4 平台旋转  方向正确   -> +1   （2026-10-30 改回：试过 -1，实测反而转错方向）
 *      M5 抓钩      方向反了   -> -1
 *
 *  ★ 怎么改：换电机/换接线后重新点动一次，看哪个反向就翻哪个的符号。
 *    改这里不用动任何其它代码 —— 符号在 Fly_MoveRelEx() /
 *    Fly_BeltMove() 的最底层统一应用。
 *
 *  ★ 重要：符号只在【下发前】应用，软件位置 pos 始终用物理方向跟踪，
 *    所以软限位 min/max 也必须是物理方向的（见 Fly_Init 里的换算）。
 * ========================================================================= */

#define FLY_DIR_SIGN_BELT_L             (-1)
#define FLY_DIR_SIGN_BELT_R             (+1)
#define FLY_DIR_SIGN_SLIDE              (-1)
#define FLY_DIR_SIGN_SWING              (+1)
