/* =========================================================================
 *              2.1 是否启用 SN 绑定（★ 当前 = 1，必须开）
 *
 *  ★★★ 为什么必须开：不绑 SN 电机根本不工作 ★★★
 *
 *    car_cfg.h 里记录过课题二的实测结论：
 *      「电机上电后不绑定 SN，只会回 ACK、不转也不报位移」
 *      「0x0313 靠 SN 匹配来认领电机：SN 对不上，总线上没有任何电机会
 *        接受这条绑定，于是没有设备号，后面所有 0x0316/0x0408/0x0413/0x0416
 *        全部落空 —— 表现就是『上位机能开、STM32 完全不动』」
 *
 *    飞箱第一次上电就是这个现象：电机不锁死、一帧都不动。
 *    根本原因链条：
 *        没绑 SN
 *          -> 电机不响应 0x0408 查询
 *          -> Fly_VerifyAxes() 返回 0
 *          -> Fly_ConfigAxes() 的闸门把整段配置拦住（一帧 0x0316 都不发）
 *          -> 0x0413 使能也没发  ->  ★ 电机没锁死
 *          -> 点动闸门也拦住      ->  ★ 完全没反应
 *
 *  ★ 绑定填的设备号 = FLY_DEV_*（7/8/9/10/11）
 *    所以绑定【不改变】出厂设备号，只是把「SN -> 设备号」这条映射
 *    在电机内部确立下来，从此电机才认 7~11 这些地址。
 *
 *  ★ 什么时候可以关掉：确认电机掉电不丢设备号、且已绑过一次之后。
 *    但只要换过电机、或发现某台不响应，就立刻改回 1。
 * ========================================================================= */

#define FLY_USE_SN_BIND                 1

