/* =========================================================================
 *        ★★★ 2.06 核心标定常量：多少指令单位 = 1 毫米 ★★★
 *
 *  ★★★ 为什么必须改（2026-10-29 现场实测）★★★
 *
 *    原来全代码按【10 单位 / mm】写（也就是把 1 单位当 0.1mm）。
 *    实测结果：M3 下发 3000 单位，平台只走了约 3cm；
 *              M4/M5 下发 1500 单位，只转了不到 10°。
 *
 *    反推：3000 单位 -> 约 30mm  =>  100 单位/mm。
 *    也就是【原代码小了 10 倍】。这不是电机的问题，
 *    是我们把「位移单位」当成了 0.1mm（其实是 0.01mm）。
 *
 *  ★ 这个常量只影响「软件怎么把 mm 换成单位」，不影响电机本身。
 *    所有距离类参数（行程限位、点动限幅、流程位移、TOF 步长）
 *    现在全部乘以它 —— 以后标定只需要改这一个数。
 *
 *  ★ 怎么校准得更准（现场只要量一次）：
 *      让 M3 走 30000 单位，用尺量实际走了 L mm
 *      新值 = 100.0f × 300 / L
 *    例：实测只有 240mm -> 新值 = 100 × 300 / 240 = 125.0f
 *
 *  ★ 注意：这个值【只影响单位换算】。如果电机内部的轮径配置
 *    （0x0408/0x24）没生效，会和它叠在一起变成另一个比例 ——
 *    所以先用上面的方法量一次，把总的实际比例标定出来，
 *    不必去追究到底是哪一级差了多少。
 * ========================================================================= */
#define FLY_UNITS_PER_MM                100.0f

