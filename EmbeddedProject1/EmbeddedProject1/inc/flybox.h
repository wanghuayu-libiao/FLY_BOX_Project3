/**
  * @brief  对已就绪的轴做参数配置
  *
  *         顺序（照搬课题二已验证的流程，但★不改设备号★）：
  *             0x0316 参数（Byte6 bit3..0 = 该轴当前设备号，保持原值）
  *             -> 0x0408 配轮径 ×3（仅皮带轴）
  *             -> 0x0413 使能
  *             -> 0x0414 加速度 / 0x0415 速度
  *
  *         ★★ 为什么 0x0316 要发：不发就没有 0x0420 剩余位移反馈，
  *            没有反馈就无法判断到位，而没有限位挡块时「无法判断到位」
  *            就等于「随时可能撞结构」。
  *         ★★ 为什么 Byte6 填自己的设备号：0x0316 会同时改设备号，
  *            填成别的值就把出厂固定号写坏了。
  *         ★★ 同一台电机一次上电只能写一条 0x0316（写第二条会把电机写死，
  *            课题二实测过），所以内部有 s_param_written[] 保护。
  * @retval 配置成功的轴数
  */
